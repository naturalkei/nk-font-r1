"""NK Studio as a desktop app: the studio server in a native window (pywebview).

`nkfont app` starts the same localhost server as `nkfont studio` on a free port and opens it in
a native window (WebKit on macOS, so it renders fonts like Safari). Nothing new runs in the page:
Studio, Glyph Lab, Presets, Specimen and the built site are the files the browser version serves.

pywebview is optional (`pip install -e ".[app]"`). Without it the app falls back to the browser.
`nkfont app --install-mac-app` writes a small "NK Studio.app" launcher into ~/Applications that
runs this command with the current Python, so the app opens from Launchpad/Spotlight/Dock.
"""

from __future__ import annotations

import os
import plistlib
import stat
import sys
import threading
import webbrowser
from pathlib import Path

from .. import config
from .server import make_server

PAGES = {
    "presets": "/presets",
    "specimen": "/specimen",
    "studio": "/",
    "lab": "/lab",
    "lab-advanced": "/lab/advanced",
    "site": "/site/",
    "update": "/update",
}
BUNDLE_ID = "dev.nk-font.studio"


def _menu(webview, base: str):
    """App menu entries that switch between the studio pages (pywebview >= 5)."""
    try:
        from webview.menu import Menu, MenuAction
    except ImportError:
        return None

    def go(path: str):
        return lambda: webview.windows[0].load_url(base + path)

    return [
        Menu(
            "보기",
            [
                MenuAction("프리셋 비교", go(PAGES["presets"])),
                MenuAction("스페시먼 (워크벤치)", go(PAGES["specimen"])),
                MenuAction("한글 미세 조절 (Studio)", go(PAGES["studio"])),
                MenuAction("글리프 랩 (기준 글자)", go(PAGES["lab"])),
                MenuAction("글리프 랩 · 고급 측정", go(PAGES["lab-advanced"])),
                MenuAction("미리보기 사이트", go(PAGES["site"])),
            ],
        ),
        Menu("업데이트", [MenuAction("업데이트 확인…", go(PAGES["update"]))]),
    ]


def _reexec(page: str) -> None:
    """Start a fresh process so updated Python code and pages are loaded."""
    os.execv(sys.executable, [sys.executable, "-m", "nkfont.cli", "app", "--page", page])


def run(page: str = "presets", port: int = 0, debug: bool = False) -> int:
    restart_requested = threading.Event()

    def restart() -> None:  # called by /api/app/restart after an update
        restart_requested.set()
        import webview

        for w in list(webview.windows):
            w.destroy()

    httpd = make_server("127.0.0.1", port, restart=restart)
    base = f"http://127.0.0.1:{httpd.server_address[1]}"
    url = base + PAGES.get(page, "/")
    threading.Thread(target=httpd.serve_forever, daemon=True).start()
    try:
        import webview
    except ImportError:
        print('pywebview is not installed: `pip install -e ".[app]"` for the window.')
        print(f"Opening {url} in the browser instead (Ctrl+C to stop).")
        webbrowser.open(url)
        try:
            threading.Event().wait()
        except KeyboardInterrupt:
            pass
        return 0
    print(f"NK Studio app on {base}")
    webview.create_window("NK Studio", url, width=1440, height=920, min_size=(900, 600))
    menu = _menu(webview, base)
    try:
        webview.start(debug=debug, menu=menu) if menu else webview.start(debug=debug)
    finally:
        httpd.shutdown()
        httpd.server_close()
    if restart_requested.is_set():
        _reexec(page)
    return 0


def mac_app_bundle(dest: Path, python: str = sys.executable, root: Path = config.ROOT) -> Path:
    """Write `<dest>/NK Studio.app`: Info.plist plus a shell launcher. Returns the bundle path."""
    app = dest / "NK Studio.app"
    macos = app / "Contents" / "MacOS"
    macos.mkdir(parents=True, exist_ok=True)
    info = {
        "CFBundleName": "NK Studio",
        "CFBundleDisplayName": "NK Studio",
        "CFBundleIdentifier": BUNDLE_ID,
        "CFBundleExecutable": "nk-studio",
        "CFBundlePackageType": "APPL",
        "CFBundleShortVersionString": "0.1.0",
        "LSMinimumSystemVersion": "11.0",
        "NSHighResolutionCapable": True,
    }
    (app / "Contents" / "Info.plist").write_bytes(plistlib.dumps(info))
    launcher = macos / "nk-studio"
    launcher.write_text(
        "#!/bin/sh\n"
        "# Generated by `nkfont app --install-mac-app`; re-run it after moving the repo or venv.\n"
        f'cd "{root}" || exit 1\n'
        f'exec "{python}" -m nkfont.cli app "$@"\n',
        encoding="utf-8",
    )
    launcher.chmod(launcher.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    return app
